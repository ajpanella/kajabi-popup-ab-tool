const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const engine = require('../experiments/engine');
const root = path.resolve(__dirname, '..');
const file = path.join(root, 'popup/variants.js');
const context = {window:{}};
vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
const config = engine.clone(context.window.LL_POPUP_CONFIG);
const queueId = 'button-color-size-20261011';
if (config.experiment?.queueId === queueId) throw new Error('This round is already prepared. Refusing to reset it.');
const previousRound = config.experiment;
const control = engine.clone(config.variants.find(v=>v.id === 'C'));
assert(control, 'Control C must exist');
const now = new Date().toISOString();
const date = new Intl.DateTimeFormat('en-US', {timeZone:'America/New_York'}).format(new Date(now));
fs.writeFileSync('/tmp/protein-control-before-button-test.json', JSON.stringify(control, null, 2));
config.variants = ['A', 'B', 'C'].map((id, index)=>{
  if (id === 'C') return control;
  const variant = engine.clone(control);
  variant.id = id;
  variant.trafficSplit = index === 0 ? 34 : 33;
  variant.name = id === 'A' ? 'Green + Larger CTA' : 'Orange + Larger CTA';
  variant.trackingLabel = variant.name;
  variant.trackingLabelManual = true;
  variant.trackingSources = [];
  if (id === 'A') variant.accentColor = control.flowSteps[0].progressColor || control.brandAccentColor;
  variant.flowSteps.forEach(step=>{
    if (step.type !== 'lead') return;
    step.buttonColor = variant.accentColor;
    step.buttonFontSize = 32;
    step.buttonMobileFontSize = 24;
  });
  const snapshot = JSON.parse(control.trackingFingerprint);
  snapshot.accentColor = variant.accentColor;
  snapshot.flowSteps = engine.clone(variant.flowSteps);
  variant.trackingFingerprint = JSON.stringify(snapshot);
  variant.trackingVersion = date + ' · ' + (id === 'A' ? 'green-large-cta-' : 'orange-large-cta-') + crypto.createHash('sha256').update(variant.trackingFingerprint).digest('hex').slice(0,8);
  variant.trackingStartedAt = now;
  return variant;
});
config.configVersion = date;
config.publishedAt = now;
config.publishId = 'button-treatment-' + now.replace(/[^0-9]/g, '');
config.dashboardDraftResetToken = config.publishId;
config.changeNote = 'A/B cloned from unchanged C. A: matching green button, larger white text. B: orange button, same larger white text. A vs B isolates color; B vs C isolates text size. Owner-requested new round.';
config.experiment = engine.createRound(config, 'C', 'button-treatment', 'Compare green versus orange at the same larger text size (A vs B), and larger versus current text on orange (B vs C). Keep all copy, images, fields and timing identical to C.', now, queueId);
config.experimentLog = (config.experimentLog || []).concat([{roundId:previousRound.id, finishedAt:now, queueId:previousRound.queueId || '',nextQueueId:queueId,decision:'user-requested-replacement',retainedVariant:'C'}]);
assert.equal(engine.validateRound(config), '');
assert.deepEqual(config.variants[2], control);
const monitorFile = path.join(root, 'experiments/high-protein-monitor.json');
const historyFile = path.join(root, 'experiments/round-history.json');
const previous = JSON.parse(fs.readFileSync(monitorFile, 'utf8'));
const history = JSON.parse(fs.readFileSync(historyFile, 'utf8'));
if (previous.roundId === previousRound.id) {
  history.push({...previous, status:'user-replaced', reason:'Owner started a new button test before scheduled review. No statistical winner was declared.', archivedAt:now});
  fs.writeFileSync(historyFile, JSON.stringify(history, null, 2) + '\n');
}
fs.writeFileSync(file, '(function () {\n  window.LL_POPUP_CONFIG = ' + JSON.stringify(config, null, 2) + ';\n})();\n');
fs.writeFileSync(monitorFile, JSON.stringify({schemaVersion:1,roundId:config.experiment.id,checkedAt:now,status:'collecting',reason:'New owner-approved button round. Waiting for fresh round sessions.',metrics:[],looks:[]}, null, 2) + '\n');
console.log('Prepared ' + config.experiment.id + '; C is byte-for-byte unchanged as a config object.');
